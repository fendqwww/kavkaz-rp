    },
    street = {
        'Голосует клиент: %s.',
        'Рядом машут рукой: %s.',
    },
}

function Phrases.pick(persona, kind)
    local own = Phrases[persona] and Phrases[persona][kind]
    local list = (own and #own > 0) and own or Phrases.generic[kind]
    if not list or #list == 0 then return nil end
    return list[math.random(#list)]
end
